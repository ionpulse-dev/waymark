//! Generated index files (see `specs/features/quality-checks`).
//!
//! An index file is a normal document `<folder>/index.md` with the tag `index` and a marker line.

use crate::format::{self, Document};
use crate::store::{Doc, Scope, Store};
use std::collections::BTreeSet;

pub const MARKER: &str = "<!-- generated by waymark index -->";

/// The ID of the index of a folder. `""` is the root.
pub fn index_id(folder: &str) -> String {
    if folder.is_empty() {
        "index".to_string()
    } else {
        format!("{folder}/index")
    }
}

pub fn parent(id: &str) -> &str {
    id.rsplit_once('/').map(|(p, _)| p).unwrap_or("")
}

/// Every folder that holds a document or a subfolder, including the root.
fn all_folders(store: &Store) -> BTreeSet<String> {
    let mut set = BTreeSet::new();
    set.insert(String::new());
    for d in store.docs() {
        let mut p = parent(&d.id);
        while !p.is_empty() {
            set.insert(p.to_string());
            p = parent(p);
        }
    }
    set
}

fn name_of(path: &str) -> &str {
    path.rsplit('/').next().unwrap_or(path)
}

fn clean(text: &str) -> String {
    text.replace('[', "(").replace(']', ")")
}

/// The body of the index of a folder: the subfolders in scope, then the documents.
pub fn body_for(store: &Store, folder: &str, subfolders: &[String]) -> String {
    let mut docs: Vec<&Doc> = store.docs().filter(|d| parent(&d.id) == folder).collect();
    docs.sort_by(|a, b| {
        a.title()
            .to_lowercase()
            .cmp(&b.title().to_lowercase())
            .then_with(|| a.id.cmp(&b.id))
    });
    let mut out = format!("\n{MARKER}\n");
    if !subfolders.is_empty() {
        out.push_str("\n## Folders\n\n");
        for f in subfolders {
            let n = name_of(f);
            out.push_str(&format!("- [{n}/]({n}/index.md)\n"));
        }
    }
    if !docs.is_empty() {
        out.push_str("\n## Documents\n\n");
        for d in docs {
            out.push_str(&format!(
                "- [{}]({}.md): {}\n",
                clean(d.title()),
                name_of(&d.id),
                d.description().replace('\n', " ")
            ));
        }
    }
    out
}

pub enum Action {
    /// Write this text (a new file or a changed one).
    Write {
        id: String,
        text: String,
        created: bool,
    },
    Unchanged(String),
    Skipped {
        id: String,
        reason: String,
    },
}

/// Plan the index files for the folders in scope. `author` is `Name <email>`.
pub fn plan(store: &Store, scope: &Scope, author: &str, today: &str) -> Vec<Action> {
    let folders = all_folders(store);
    let in_scope: Vec<&String> = folders
        .iter()
        .filter(|f| scope.allows(&index_id(f)))
        .collect();
    let mut actions = Vec::new();
    for folder in &in_scope {
        let id = index_id(folder);
        let subfolders: Vec<String> = in_scope
            .iter()
            .filter(|f| !f.is_empty() && parent(f) == folder.as_str())
            .map(|f| (*f).clone())
            .collect();
        let has_content =
            store.docs().any(|d| parent(&d.id) == folder.as_str()) || !subfolders.is_empty();
        if !has_content {
            continue;
        }
        let body = body_for(store, folder, &subfolders);
        match store.get(&id) {
            Some(existing) if !existing.is_index() => actions.push(Action::Skipped {
                id,
                reason: "A document with this name exists and is not generated.".into(),
            }),
            Some(existing) => {
                if existing.body.trim() == body.trim() {
                    actions.push(Action::Unchanged(id));
                    continue;
                }
                let Ok(mut doc) = format::parse(&existing.raw) else {
                    continue;
                };
                doc.body = body;
                doc.frontmatter.set_date("updated", today);
                doc.frontmatter.set_text("updated_by", author);
                actions.push(Action::Write {
                    id,
                    text: doc.render(),
                    created: false,
                });
            }
            None => {
                let (title, description) = if folder.is_empty() {
                    (
                        "Index".to_string(),
                        "Generated list of the documents in the memory repository.".to_string(),
                    )
                } else {
                    (
                        format!("Index of {folder}"),
                        format!("Generated list of the documents in {folder}."),
                    )
                };
                let mut doc = Document::new(&body);
                let fm = &mut doc.frontmatter;
                fm.set_text("title", &title);
                fm.set_text("description", &description);
                fm.set_text("status", "active");
                fm.set_date("created", today);
                fm.set_date("updated", today);
                fm.set_text("created_by", author);
                fm.set_text("updated_by", author);
                fm.set_list("tags", &["index".to_string()]);
                actions.push(Action::Write {
                    id,
                    text: doc.render(),
                    created: true,
                });
            }
        }
    }
    actions
}

/// The folder that an index ID belongs to (`backend/index` is `backend`).
pub fn folder_of_index(id: &str) -> &str {
    parent(id)
}

/// The expected body of an existing index, for `index-stale`. `scope_all` has no limits.
pub fn expected_body(store: &Store, folder: &str, scope: &Scope) -> String {
    let folders = all_folders(store);
    let subfolders: Vec<String> = folders
        .iter()
        .filter(|f| !f.is_empty() && parent(f) == folder && scope.allows(&index_id(f)))
        .cloned()
        .collect();
    body_for(store, folder, &subfolders)
}
